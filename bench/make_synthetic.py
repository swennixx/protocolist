SCRIPTS = {"sfera": SFERA, "client": CLIENT}


def main(name: str = "sfera") -> None:
    os.makedirs(OUT, exist_ok=True)
    tmp = tempfile.mkdtemp()
    parts, turns, t = [], [], 0.0
    script = SCRIPTS[name]
    for i, (spk, text) in enumerate(script):
        aiff, wav = os.path.join(tmp, f"{i}.aiff"), os.path.join(tmp, f"{i}.wav")
        subprocess.run(["say", "-v", "Milena", "-r", "175", "-o", aiff, text], check=True)
        f = PITCH[spk]
        # change pitch, keep tempo: resample by f, then stretch time back
        af = f"asetrate={int(22050 * f)},aresample={SR},atempo={1 / f:.4f}"
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", aiff, "-af", af, "-ac", "1", "-ar", str(SR), wav], check=True)
        dur = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", wav],
                                   capture_output=True, text=True, check=True).stdout)
        pause = 0.5 + (i * 7 % 5) / 10
        silence = os.path.join(tmp, f"{i}s.wav")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i", f"anullsrc=r={SR}:cl=mono", "-t", str(pause), silence], check=True)
        parts += [wav, silence]
        turns.append({"speaker": spk, "start": round(t, 3), "end": round(t + dur, 3), "text": text})
        t += dur + pause
    lst = os.path.join(tmp, "list.txt")
    with open(lst, "w") as fh:
        fh.writelines(f"file '{p}'\n" for p in parts)
    out = os.path.join(OUT, f"{name}.wav")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", lst, "-c", "copy", out], check=True)
    with open(os.path.join(OUT, f"{name}.json"), "w", encoding="utf-8") as fh:
        json.dump({"speakers": len({spk for spk, _ in script}), "turns": turns}, fh, ensure_ascii=False, indent=1)
    print(f"{out}: {t:.1f} s, {len(turns)} turns")


if __name__ == "__main__":
    import sys

    for n in sys.argv[1:] or SCRIPTS:
        main(n)
